from nodes import *
from token_types import TokenTypes as TT
import operator
from errors import RunePlusPlusError

class Evaluator:
    """
    Recursively traverses (depth-first) the abstract syntax tree generated by the lexer
    and performs the necessary actions (such as addition, multiplication etc)
    """

    # Maps TokenType to functions for binary operations
    BINARY_TT_TO_FUNCTION_DICT = {
        TT.ADD: operator.add,
        TT.MINUS: operator.sub,
        TT.MULTIPLY: operator.mul,
        TT.DIVIDE: operator.truediv,
        TT.LESS_THAN: operator.lt,
        TT.MORE_THAN: operator.gt,
        TT.EQUALS: operator.eq,
        TT.AND: operator.and_, # Bitwise 'and', but should be fine for booleans
        TT.OR: operator.or_ # Bitwise 'or', but should be fine for booleans
    }

    # Maps TokenType to functions for unary operations
    UNARY_TT_TO_FUNCTION_DICT = {
        TT.MINUS: lambda num: operator.mul(num, -1), # negates the number
        TT.NOT: operator.not_
    }

    def __init__(self, root_node):
        self.root_node = root_node

        # Stores the function that should be applied to each type of node
        self.node_to_function_dict = {
            NumberNode: self.process_number_node,
            BinaryOperationNode: self.process_binary_operation_node,
            UnaryOperationNode: self.process_unary_operation_node,
            VariableAssignmentNode: self.process_variable_assignment_node,
            VariableReadNode: self.process_variable_read_node,
            IfStatementNode: self.process_if_statement_node,
            WhileNode: self.process_while_node,
            FunctionDefinitionNode: self.process_function_definition_node
        }

    def traverse(self, context, node=None):
        """
        Traverses the given node, performing any necessary functions and recursively
        calling traverse() on any children nodes
        """
        # By default set node as self.root_node - this can't be done directly in the
        # function definition
        if node is None:
            node = self.root_node

        node_function = self.node_to_function_dict[type(node)]

        return node_function(context, node)

    def process_number_node(self, context, node):
        """
        Returns the number value (integer or float) of the number node
        """
        return node.token.value

    def process_binary_operation_node(self, context, node):
        """
        Runs any necessary computations on the binary operation node and recursively
        traverses the children nodes
        """
        left_result = self.traverse(context, node.left_node)
        right_result = self.traverse(context, node.right_node)

        return self.BINARY_TT_TO_FUNCTION_DICT[node.operator_token.token_type](
            left_result,
            right_result
        )

    def process_unary_operation_node(self, context, node):
        """
        Runs any necessary computations on the number node and recursively traverses its
        child node
        """
        operand_result = self.traverse(context, node.operand_node)

        return self.UNARY_TT_TO_FUNCTION_DICT[node.operator_token.token_type](
            operand_result
        )

    def process_variable_assignment_node(self, context, node):
        """Assigns the value to the variable in the context's symbol table"""
        variable_name = node.variable_name_token.value
        value = self.traverse(context, node.value_node)

        context.symbol_table.set(variable_name, value)

        return value

    def process_variable_read_node(self, context, node):
        """Reads the value stored in the variable"""
        variable_name = node.variable_name_token.value
        read_value = context.symbol_table.get(variable_name)

        if read_value is None:
            raise RunePlusPlusError(f"Variable '{variable_name}' doesn't exist!")

        return read_value

    def process_if_statement_node(self, context, node):
        """Runs the if statement"""
        for condition, body in node.if_cases:
            condition_result = self.traverse(context, condition)

            if condition_result:
                 return self.traverse(context, body)

        if node.else_case:
            return self.traverse(context, node.else_case)

    def process_while_node(self, context, node):
        """
        Runs the while loop until the condition is no longer met. I originally tried
        implementing while loops without calling Python's 'while' keyword directly (to
        avoid being just a reskin of Python), however using recursion means that there
        is a limit to how many iterations can be performed. Therefore I've just used a
        while loop.
        """
        while self.traverse(context, node.condition):
            # Run the body of the loop
            self.traverse(context, node.body)

    def process_function_definition_node(self, context, node):
        "Saves the FunctionDefinitionNode as a variable in the symbol table"
        context.symbol_table.set(node.name_token.value, node)
